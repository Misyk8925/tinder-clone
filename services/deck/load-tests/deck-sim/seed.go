package main

import (
	"bufio"
	"fmt"
	"io"
	"strings"
)

// WriteSeedSQL emits the SQL that puts a generated population into the profiles database.
//
// SQL rather than a database driver so this tool keeps needing nothing but the Go toolchain.
// Piping it into psql is one more shell step and one fewer dependency.
//
// Two deliberate simplifications, both of which are stated rather than hidden:
//
//   - `user_id` is set to the profile id. They are genuinely different things — one is a
//     Keycloak subject, the other a Profiles aggregate id — and deck-read resolves between
//     them. Making them equal turns that mapping into the identity, so the simulator's single
//     id works as both the token subject and the swipe's profile id.
//   - `preferences.gender` is `all`. The simulator models taste, distance and age but not
//     gender, so any other value would filter candidates on a dimension the decision model
//     does not have, and the ranking comparison would be measuring that filter.
//
// Preference rows are *interned*, not one per profile: the table carries
// `UNIQUE (min_age, max_age, gender, max_range)`, so every profile wanting the same thing
// shares a row. Their ids are therefore derived from the tuple, never from the agent.
func WriteSeedSQL(out io.Writer, agents []Agent, batch int) error {
	writer := bufio.NewWriterSize(out, 1<<20)
	defer writer.Flush()

	fmt.Fprintln(writer, "-- Generated by deck-sim seed. Disposable bench data.")
	fmt.Fprintln(writer, "BEGIN;")

	if err := writeBatched(writer, agents, batch,
		"INSERT INTO location (id, city, geo, created_at, updated_at) VALUES",
		func(agent Agent) string {
			return fmt.Sprintf("('%s','%s',ST_SetSRID(ST_MakePoint(%.6f,%.6f),4326)::geography,now(),now())",
				locationID(agent), city(agent), agent.Longitude, agent.Latitude)
		}); err != nil {
		return err
	}

	if err := writeBatched(writer, agents, batch,
		"INSERT INTO preferences (id, gender, min_age, max_age, max_range) VALUES",
		func(agent Agent) string {
			return fmt.Sprintf("('%s','all',%d,%d,%d)",
				preferencesID(agent), agent.MinAge, agent.MaxAge, agent.MaxRangeKm)
		}); err != nil {
		return err
	}

	if err := writeBatched(writer, agents, batch,
		"INSERT INTO profiles (id, user_id, name, age, gender, bio, city, is_active, is_deleted, "+
			"is_premium, version, location_id, preferences_id, created_at, updated_at) VALUES",
		func(agent Agent) string {
			return fmt.Sprintf("('%s','%s','%s',%d,'%s','%s','%s',true,false,false,0,'%s','%s',now(),now())",
				agent.ID, agent.ID, name(agent), agent.Age, gender(agent), "simulated", city(agent),
				locationID(agent), preferencesID(agent))
		}); err != nil {
		return err
	}

	fmt.Fprintln(writer, "COMMIT;")
	return writer.Flush()
}

func writeBatched(writer io.Writer, agents []Agent, batch int, header string, row func(Agent) string) error {
	if batch <= 0 {
		batch = 1000
	}
	for start := 0; start < len(agents); start += batch {
		end := start + batch
		if end > len(agents) {
			end = len(agents)
		}
		values := make([]string, 0, end-start)
		for _, agent := range agents[start:end] {
			values = append(values, row(agent))
		}
		if _, err := fmt.Fprintf(writer, "%s\n%s\nON CONFLICT DO NOTHING;\n",
			header, strings.Join(values, ",\n")); err != nil {
			return err
		}
	}
	return nil
}

// A location belongs to exactly one profile and the table has no constraint beyond its key,
// so the profile's own id serves.
func locationID(agent Agent) string { return agent.ID }

// A preference row is shared by every profile that wants the same thing, so its id has to be
// a function of the tuple. Deriving it from the agent instead produced one id per profile
// against a table that keeps one row per combination: the inserts collapsed under
// ON CONFLICT and every profile then pointed at a preference row that was never written.
func preferencesID(agent Agent) string {
	return preferenceKey(agent.MinAge, agent.MaxAge, agent.MaxRangeKm, "all")
}

func preferenceKey(minAge, maxAge, maxRange int, gender string) string {
	seed := fmt.Sprintf("%d:%d:%d:%s", minAge, maxAge, maxRange, gender)
	high := fnv1a64(seed)
	low := fnv1a64WithSeed(seed, high)
	return fmt.Sprintf("%08x-%04x-4%03x-8%03x-%012x",
		uint32(high>>32), uint16(high>>16), uint16(high)&0x0fff,
		uint16(low>>48)&0x0fff, low&0xffffffffffff)
}

// The simulator has no gender, and neither does SharedProfileDto — but the profiles table
// requires one. Derived from the id so it is stable, and never used by the ranking.
func gender(agent Agent) string {
	if fnv1a64(agent.ID)%2 == 0 {
		return "male"
	}
	return "female"
}

func name(agent Agent) string {
	return "sim-" + agent.ID[:8]
}

func city(agent Agent) string {
	return fmt.Sprintf("sim-%d-%d", int(agent.Latitude), int(agent.Longitude))
}
